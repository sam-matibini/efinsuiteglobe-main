/**
 * Bundle the CRA gateway into plain JavaScript for the Vercel Node runtime.
 * Vercel's TypeScript compile rejects `.ts` import specifiers, and that crash
 * surfaced as FUNCTION_INVOCATION_FAILED on /api/cra-gateway.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outfile = path.join(root, 'api', 'cra-gateway.js');

function dotenvValue(name) {
  const fromProcess = process.env[name];
  if (fromProcess && fromProcess.trim()) return fromProcess.trim();
  const file = path.join(root, '.env');
  if (!fs.existsSync(file)) return '';
  const line = fs.readFileSync(file, 'utf8').split('\n').find((entry) => entry.startsWith(`${name}=`));
  if (!line) return '';
  return line.slice(name.length + 1).trim().replace(/^["']|["']$/g, '');
}

const supabaseUrl = dotenvValue('VITE_SUPABASE_URL') || dotenvValue('SUPABASE_URL');
const anonKey = dotenvValue('VITE_SUPABASE_PUBLISHABLE_KEY') || dotenvValue('SUPABASE_PUBLISHABLE_KEY');

await build({
  absWorkingDir: root,
  entryPoints: [path.join(root, 'server', 'craGatewayHandler.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  legalComments: 'none',
  external: ['@supabase/supabase-js'],
  define: {
    'process.env.CRA_BUNDLE_SUPABASE_URL': JSON.stringify(supabaseUrl),
    'process.env.CRA_BUNDLE_SUPABASE_ANON_KEY': JSON.stringify(anonKey),
  },
  banner: {
    js: '// Generated by scripts/bundle-cra-gateway.mjs. Edit server/craGatewayHandler.ts instead.',
  },
});

const source = fs.readFileSync(outfile, 'utf8');
if (source.includes('.ts"') || source.includes("from \"../supabase")) {
  console.error('cra-gateway bundle still imports TypeScript source.');
  process.exit(1);
}
if (!supabaseUrl || !anonKey) {
  console.error('cra-gateway bundle is missing the public Supabase URL or publishable key.');
  process.exit(1);
}

const { default: handler } = await import(`${pathToFileURL(outfile).href}?smoke=${Date.now()}`);
const node = await capture(handler, { method: 'POST', headers: {}, body: {} });
const web = await handler(new Request('http://127.0.0.1/api/cra-gateway', {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: '{}',
}));
const webBody = await web.json();
if (node.status !== 401 || node.body?.error !== 'Sign in before using the CRA gateway.') {
  console.error('node smoke failed', node.status);
  process.exit(1);
}
if (web.status !== 401 || webBody?.error !== 'Sign in before using the CRA gateway.') {
  console.error('web smoke failed', web.status);
  process.exit(1);
}

console.log(`cra-gateway bundle: ${source.length} bytes, unsigned POST returns 401`);

function capture(fn, req) {
  let status = 0;
  let body = null;
  const res = {
    status(code) {
      status = code;
      return this;
    },
    json(payload) {
      body = payload;
    },
  };
  return Promise.resolve(fn(req, res)).then(() => ({ status, body }));
}
